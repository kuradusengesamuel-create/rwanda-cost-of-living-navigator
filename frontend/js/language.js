let currentLanguage = localStorage.getItem("clnp_language") || "en";

function applyTranslations(lang) {
  var t = translations[lang];
  if (!t) return;
  Object.keys(t).forEach(function (id) {
    var element = document.getElementById(id);
    if (element) {
      element.innerHTML = t[id];
    }
  });
  document.documentElement.lang = lang === "rw" ? "rw" : "en";
}

function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem("clnp_language", currentLanguage);
  applyTranslations(currentLanguage);
  var btnEn = document.getElementById("btn-en");
  var btnRw = document.getElementById("btn-rw");
  if (btnEn && btnRw) {
    if (lang === "en") {
      btnEn.style.background = "rgba(255,255,255,0.9)";
      btnEn.style.color = "#0066CC";
      btnRw.style.background = "transparent";
      btnRw.style.color = "rgba(255,255,255,0.8)";
    } else {
      btnRw.style.background = "rgba(255,255,255,0.9)";
      btnRw.style.color = "#0066CC";
      btnEn.style.background = "transparent";
      btnEn.style.color = "rgba(255,255,255,0.8)";
    }
  }
}

function toggleLanguage() {
  setLanguage(currentLanguage === "en" ? "rw" : "en");
}

function getCurrentLanguage() {
  return currentLanguage;
}

document.addEventListener("DOMContentLoaded", function () {
  applyTranslations(currentLanguage);
  setLanguage(currentLanguage);
});

window.setLanguage = setLanguage;
window.toggleLanguage = toggleLanguage;
window.getCurrentLanguage = getCurrentLanguage;
